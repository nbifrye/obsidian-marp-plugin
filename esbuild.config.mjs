import esbuild from 'esbuild';
import process from 'process';
import {
	assetQueryPlugin,
	checkNoNodeBuiltins,
} from './scripts/esbuild-plugins.mjs';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		// Node builtins are not external: the plugin runs on mobile too, and
		// packages' "browser" fields replace the ones they import (postcss).
	],
	// Marp Core picks Node-only internals through the "node" export condition,
	// so build for the browser to get the implementations that run on mobile.
	platform: 'browser',
	plugins: [assetQueryPlugin],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	metafile: prod,
});

if (prod) {
	const result = await context.rebuild();
	checkNoNodeBuiltins(result.metafile);
	process.exit(0);
} else {
	await context.watch();
}
